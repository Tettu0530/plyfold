//! Local history and checkout in one worktree. Remote refs are the ones already fetched by Git.

use std::path::Path;

use serde::{Deserialize, Serialize};

use crate::{WorktreeError, git};

const HISTORY_LIMIT: usize = 150;

#[derive(Debug, Serialize)]
pub struct History {
    pub branch: Option<String>,
    pub head: Option<String>,
    pub branches: Vec<Branch>,
    pub rows: Vec<GraphRow>,
    pub truncated: bool,
}

#[derive(Debug, Serialize)]
pub struct Branch {
    pub name: String,
    pub sha: String,
    pub remote: bool,
}

#[derive(Debug, Serialize)]
pub struct GraphRow {
    /// Lane connectors generated by Git, including connector-only rows after a merge.
    pub graph: String,
    pub commit: Option<HistoryCommit>,
}

#[derive(Debug, Serialize)]
pub struct HistoryCommit {
    pub sha: String,
    pub short_sha: String,
    pub subject: String,
}

#[derive(Debug, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum Checkout {
    Local { name: String },
    Remote { name: String },
    NewBranch { name: String },
    Commit { sha: String },
}

pub fn history(dir: &Path) -> Result<History, WorktreeError> {
    let head = crate::head(dir);
    let branch = git(dir, &["symbolic-ref", "--quiet", "HEAD"]).ok().and_then(|s| s.trim().strip_prefix("refs/heads/").map(str::to_owned));
    let refs = git(dir, &["for-each-ref", "--format=%(refname)%00%(objectname)%00%(symref)", "refs/heads", "refs/remotes"])?;
    let branches = refs
        .lines()
        .filter_map(|line| {
            let mut fields = line.split('\0');
            let reference = fields.next()?;
            let sha = fields.next()?.to_owned();
            if !fields.next()?.is_empty() {
                return None; // E.g. origin/HEAD repeats a branch already in the list.
            }
            let (name, remote) =
                reference.strip_prefix("refs/heads/").map(|name| (name, false)).or_else(|| reference.strip_prefix("refs/remotes/").map(|name| (name, true)))?;
            Some(Branch { name: name.to_owned(), sha, remote })
        })
        .collect();

    let count = format!("--max-count={}", HISTORY_LIMIT + 1);
    let mut args = vec![
        "log",
        "--graph",
        "--topo-order",
        "--no-color",
        "--no-decorate",
        "--no-show-signature",
        "--no-notes",
        "--no-patch",
        "--format=%x00%H%x00%h%x00%s",
        &count,
        "--branches",
        "--remotes",
    ];
    if let Some(sha) = head.as_deref() {
        args.push(sha); // A detached HEAD need not be reachable from any branch.
    }
    args.push("--");
    let mut rows = Vec::new();
    let mut commits = 0;
    let mut truncated = false;
    for line in git(dir, &args)?.lines() {
        let mut fields = line.splitn(4, '\0');
        let graph = fields.next().unwrap_or_default().to_owned();
        let commit = fields.next().map(|sha| HistoryCommit {
            sha: sha.to_owned(),
            short_sha: fields.next().unwrap_or_default().to_owned(),
            subject: fields.next().unwrap_or_default().to_owned(),
        });
        if commit.is_some() {
            if commits == HISTORY_LIMIT {
                truncated = true;
                break;
            }
            commits += 1;
        }
        rows.push(GraphRow { graph, commit });
    }
    Ok(History { branch, head, branches, rows, truncated })
}

pub fn checkout(dir: &Path, target: Checkout) -> Result<(), WorktreeError> {
    let switch = ["switch", "--no-guess", "--no-overwrite-ignore", "--no-recurse-submodules"];
    let invalid =
        || WorktreeError::Op(plyfold_i18n::tr!("ブランチ名またはコミット ID が無効です", "Invalid branch name or commit ID", "分支名称或提交 ID 无效"));
    let mut args = switch.to_vec();
    let remote_ref;
    match &target {
        Checkout::Local { name } | Checkout::NewBranch { name } => {
            if name.starts_with('-') || name == "HEAD" {
                return Err(invalid());
            }
            let reference = format!("refs/heads/{name}");
            git(dir, &["check-ref-format", &reference]).map_err(|_| invalid())?;
            if matches!(target, Checkout::NewBranch { .. }) {
                args.extend(["-c", name]);
            } else {
                git(dir, &["show-ref", "--verify", &reference])?;
                args.extend(["--", name]);
            }
        }
        Checkout::Remote { name } => {
            remote_ref = format!("refs/remotes/{name}");
            git(dir, &["check-ref-format", &remote_ref]).map_err(|_| invalid())?;
            git(dir, &["show-ref", "--verify", &remote_ref])?;
            args.extend(["--track", "--", &remote_ref]);
        }
        Checkout::Commit { sha } => {
            if !matches!(sha.len(), 40 | 64) || !sha.bytes().all(|c| c.is_ascii_hexdigit()) {
                return Err(invalid());
            }
            args.extend(["--detach", "--", sha]);
        }
    }
    git(dir, &args).map(|_| ())
}
